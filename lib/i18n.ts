export async function getLocale(): Promise<Locale> {
  const jar = await cookies();
  return jar.get("locale")?.value === "vi" ? "vi" : "en";
}

export async function getI18n() {
  const locale = await getLocale();
  const t = locale === "vi" ? vi : en;
  return { locale, t };
}
